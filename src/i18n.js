export const languages = ['zh-CN', 'ja', 'en'];
export const languageKey = 'zhijian-language';

export function resolveLanguage(value) {
  const base = String(value || '').toLowerCase().split('-')[0];
  return base === 'zh' ? 'zh-CN' : base === 'ja' || base === 'en' ? base : null;
}

export function detectLanguage(saved, preferred = []) {
  return resolveLanguage(saved) || preferred.map(resolveLanguage).find(Boolean) || 'zh-CN';
}

let language = 'zh-CN';
export const getLanguage = () => language;
export function setLanguage(value) {
  if (languages.includes(value)) language = value;
}

// 中文原文作为键；插值只替换参数，不解释 HTML。
export function tr(key, values = {}) {
  const message = language === 'zh-CN' ? key : messages[key]?.[language === 'en' ? 0 : 1] ?? key;
  return message.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}

